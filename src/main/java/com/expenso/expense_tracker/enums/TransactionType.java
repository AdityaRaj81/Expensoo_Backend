package com.expenso.expense_tracker.enums;

/**
 * Enum representing the types of transactions in the expense tracker application.
 *
 * <p>This enum is used to differentiate between income and expense transactions.
 * It helps in categorizing and managing financial data effectively.</p>
 *
 * <ul>
 *   <li><b>INCOME</b>: Represents a transaction where money is received.</li>
 *   <li><b>EXPENSE</b>: Represents a transaction where money is spent.</li>
 * </ul>
 */
public enum TransactionType {

    /**
     * Represents a transaction where money is received.
     */
    INCOME,

    /**
     * Represents a transaction where money is spent.
     */
    EXPENSE

}